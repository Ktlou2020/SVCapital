#!/usr/bin/env node
/* The logo on the statements and the tax certificates.
 *
 * These four documents are the ones a client keeps, prints, or hands to an
 * accountant: the account statement, the sub-account statement, and the two
 * tax certificates (investor and admin). They now carry
 * sv-capital-logo-horizontal-outline-1.png.
 *
 * That logo is DARK ARTWORK ON TRANSPARENCY, and the letterheads were built
 * around a logo that is the opposite — white text, which needs something dark
 * behind it. Two things follow, and neither of them fails loudly:
 *
 *   A dark chip behind dark artwork renders a dark smudge. The white-text logo
 *   sat in a #1f2937 chip on the admin letterheads; leaving that chip in place
 *   would have hidden the new logo on a page that otherwise looks correct.
 *
 *   The two portal statements print the logo inside a full-width #303030
 *   brand band, which carries the document title in white and amber and is not
 *   worth rebuilding to change a logo. There the logo needs a white chip
 *   instead — the inverse of the problem above.
 *
 * Neither shows up in a diff and both look fine in source. So this asserts the
 * pairing directly: dark ground implies a white chip, light ground implies no
 * chip.
 *
 * Deliberately NOT covered: emails, the marketing site, the console chrome and
 * the two pool reports, which keep the white-text logo on their dark grounds.
 *
 * Run: node scripts/check-document-letterhead.cjs
 */
'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

const LOGO     = 'sv-capital-logo-horizontal-outline-1.png';
const OLD_LOGO = 'sv-capital-logo-horizontal-white-text.png';

let pass = 0, fail = 0;
const ok = (name, cond, detail) => {
  if (cond) { pass++; console.log(`  ✓ ${name}`); }
  else { fail++; console.log(`  ✗ ${name}${detail ? `\n      ${detail}` : ''}`); }
};

/* Take the body of one named function, so an assertion about "the statement"
   cannot be satisfied by something elsewhere in a 20 000-line file. */
function fnBody(src, name) {
  const at = src.search(new RegExp(`(async\\s+)?function ${name}\\(`));
  if (at < 0) return null;
  let i = src.indexOf('{', src.indexOf('(', at)), depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') { depth--; if (depth === 0) break; }
  }
  return src.slice(at, i + 1);
}

console.log('\nthe asset is in the repository');
{
  const p = path.join(ROOT, 'assets', LOGO);
  ok('assets/' + LOGO + ' exists', fs.existsSync(p));
  ok('and is a PNG, not an LFS pointer or an empty file',
     fs.existsSync(p) && fs.readFileSync(p).slice(1, 4).toString() === 'PNG' &&
     fs.statSync(p).size > 10000,
     fs.existsSync(p) ? `${fs.statSync(p).size} bytes` : 'missing');
}

/* [file, function, description, ground] — 'light' means the logo sits on the
   white letterhead, 'dark' means it sits inside the #303030 brand band. */
const DOCUMENTS = [
  ['js/investor-documents.js', '_openAdminTaxCertWindow',     'the tax certificate',   'light'],
  ['js/investor-documents.js', '_openAccountStatementWindow', 'the account statement', 'light'],
  ['js/portal-core.js',   'downloadSaStatement',         'the sub-account statement',   'dark'],
];

/* The investor's certificate and statement no longer carry a letterhead of
   their own — they render the shared document above. What is asserted of them
   is that they still delegate rather than growing a second copy. */
const DELEGATES = [
  ['js/portal-core.js', 'generateTaxCertificate', 'SVCDocs.openIncomeReference',  'the investor income reference'],
  ['js/portal-core.js', 'generateStatement',      'SVCDocs.accountStatementHTML', 'the investor statement'],
];

console.log('\nevery statement and tax certificate carries the new logo');
for (const [file, fn, what, ground] of DOCUMENTS) {
  const body = fnBody(read(file), fn);
  ok(`${what} is generated by ${fn}`, !!body, `${fn} not found in ${file}`);
  if (!body) continue;

  ok(`${what} uses the new logo`,
     body.includes(LOGO), `${file} › ${fn} still points at something else`);
  ok(`${what} no longer uses the white-text logo`,
     !body.includes(OLD_LOGO),
     'the white-text logo is for dark grounds — emails, the site, the console');

  /* The chip is the part that does not fail loudly. The letterhead <img> takes
     its src either from the filename directly or through a logoUrl variable,
     so find the tag first and then read what wraps it. */
  const IMG = new RegExp(`<img[^>]*src="(?:[^"]*${LOGO.replace(/[.]/g, '\\.')}|\\$\\{_?logoUrl\\})[^"]*"[^>]*>`, 'i');
  /* One of these documents is built by joining an array of string literals, so
     the src is spliced in with + rather than interpolated. Same markup either
     way once the seam is closed. */
  const flat = body.replace(/'\s*\+\s*_?logoUrl\s*\+\s*'/g, '${logoUrl}');
  const m = flat.match(IMG);
  ok(`${what} renders a letterhead <img>`, !!m, 'no logo img found');
  const before = m ? flat.slice(Math.max(0, m.index - 160), m.index) : '';
  const darkChip  = /background:#(1f2937|303030)[^"]*"[^>]*>\s*$/i.test(before);
  const whiteChip = /background:#(fff|ffffff)[^"]*"[^>]*>\s*$/i.test(before);

  if (ground === 'light') {
    ok(`${what} puts it straight on the letterhead, with no dark chip`,
       !darkChip,
       'dark artwork on a dark chip is a smudge — the chip existed for the white-text logo');
  } else {
    ok(`${what} puts it on a white chip inside the brand band`,
       whiteChip && !darkChip,
       'the band is #303030; dark artwork on it is invisible');
  }
}

console.log('\nthe investor copies delegate rather than duplicating');
for (const [file, fn, call, what] of DELEGATES) {
  const body = fnBody(read(file), fn);
  ok(`${what} renders the shared document`,
     !!body && body.includes(call),
     `${fn} should call ${call}`);
  ok(`and builds no letterhead of its own`,
     !!body && !body.includes(OLD_LOGO) && !/<!DOCTYPE html>/i.test(body),
     'a second copy of the design is a second thing to keep in step');
}

console.log('\nthe documents survive a phone');
{
  const docs = read('js/investor-documents.js');

  /* The download is the point of the document. A phone must not change it. */
  ok('the statement is still A4 landscape',
     /@page\{size:A4 landscape/.test(docs),
     'the preview is scaled with a transform, which changes nothing about the page');
  ok('the certificate is still A4 portrait',
     /@page\{size:A4 portrait/.test(docs));

  /* window.open with window features is refused as a pop-up on mobile Safari
     and inside the Capacitor WebView. */
  ok('a blocked pop-up falls back to a full-screen overlay',
     /if \(win\) \{[\s\S]{0,120}\}\s*\n\s*_overlay\(html, width\);/.test(docs),
     'it used to tell the client to change a browser setting and give up');
  ok('and the overlay prints the FRAME, so the page rules still apply',
     /frame\.contentWindow\.print\(\)/.test(docs),
     'printing the overlay itself would print the chrome and lose @page');
  ok('nothing tells a client to allow pop-ups any more',
     !/allow pop-ups/i.test(docs));

  ok('the preview scales rather than squeezing',
     /transform-origin:top left/.test(docs) && /Math\.min\(1, avail \/ docWidth\)/.test(docs),
     'these are fixed-width documents — they do not reflow, they just overflow');
  ok('and never scales a document UP on a desktop',
     /Math\.min\(1,/.test(docs));

  const core = read('js/portal-core.js');
  ok('the portal preview uses the shared scaled mount',
     /SVCDocs\.mountScaled\(doc, SVCDocs\.accountStatementHTML/.test(core));
}

console.log('\nthe mobile build carries the same documents');
{
  /* mobile/www is a build artifact — mobile/src and js/ are the sources — so
     the risk is editing the artifact and having the next build revert it. */
  ok('js/portal-core.js and its mobile copy are byte-identical',
     read('js/portal-core.js') === read('mobile/www/js/portal-core.js'),
     'run node mobile/scripts/build.js');
  ok('the mobile statement was changed at the SOURCE, not in www',
     read('mobile/src/js/portal.js').includes(LOGO),
     'mobile/www is regenerated from mobile/src; an edit to www alone is lost');
  ok('and the built copy agrees with it',
     read('mobile/www/js/portal.js').includes(LOGO));
  ok('the asset ships with the app',
     fs.existsSync(path.join(ROOT, 'mobile', 'www', 'assets', LOGO)));
}

console.log('\nand the documents nobody asked to change were left alone');
{
  const admin = read('admin/js/admin.js');   // the pool reports still live here
  for (const fn of ['_openPoolRaiseReportWindow', '_openPoolMaturityReportWindow']) {
    const body = fnBody(admin, fn);
    ok(`${fn} keeps its existing letterhead`,
       !!body && body.includes(OLD_LOGO) && !body.includes(LOGO),
       'the request covered the statements and the tax certificate only');
  }
  ok('emails keep the white-text logo, which suits their dark header',
     read('server/services/email.js').includes(OLD_LOGO));
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
